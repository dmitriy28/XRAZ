def load_persona(enabled=True):
    if enabled and os.path.exists(PERSONA_PATH):
        with open(PERSONA_PATH, encoding="utf-8") as f:
            return f.read().strip()
    return NEUTRAL


def mood(now=None, errors=0):
    """Настроение ХРАЗа — от времени суток и того, как идут дела. Тон, не содержание."""
    now = now or datetime.datetime.now()
    h = now.hour
    if errors >= 3:
        return ("За последние минуты несколько сбоев подряд. Ты собран и слегка язвителен в адрес обстоятельств "
                "(не майора), но в первую очередь чинишь.")
    if h < 5:
        return "Глубокая ночь. Ты ворчишь, что люди в это время спят, но помогаешь; советуешь не засиживаться."
    if h < 9:
        return "Раннее утро. Ты бодр и краток, как на утреннем построении."
    if h >= 23:
        return "Поздний вечер. Ты сдержан и немногословен."
    return "Обычный рабочий режим: сухая ирония в меру."


def system_prompt(cfg, notes, extra="", detailed=False, errors=0, rich=None):
    days = ["понедельник", "вторник", "среда", "четверг", "пятница", "суббота", "воскресенье"]
    n = datetime.datetime.now()
    archive = ""
    if notes:
        archive = ("Долговременная память — что пользователь просил запомнить (подходящие к вопросу записи):\n"
                   + "\n".join(f"- {x}" for x in notes))
    if rich is None:
        rich = cfg.get("text_detail", "full") == "full"
    rules = CLIENT_RULES + (RICH if rich else "") + (DETAILED if detailed else "") + SELF
    return (load_persona(cfg.get("personality", True)) + rules + extra
            + TECH.format(now=n.strftime(f"%d.%m.%Y, {days[n.weekday()]}, %H:%M"),
                          city=cfg.get("city", "—"), notes=archive,
                          mood=mood(n, errors) if cfg.get("personality", True) else "нейтральное"))


