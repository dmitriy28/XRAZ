def say(kind, **kw):
    p = random.choice(PHRASES.get(kind, ["Готово."]))
    return p.format(**kw) if kw else p


def startup_kind(now=None):
    h = (now or datetime.datetime.now()).hour
    return "startup_night" if h < 5 else "startup_morning" if h < 11 else "startup_evening" if h >= 18 else "startup"


